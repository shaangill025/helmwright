import { createHash, timingSafeEqual } from "node:crypto";
import {
  Agent,
  createServer,
  request as httpRequest,
  type IncomingMessage,
  type ServerResponse,
} from "node:http";
import { request as httpsRequest } from "node:https";
import type { AddressInfo } from "node:net";
import {
  PRICES_VERIFIED,
  SpendLedger,
  priceOf,
  preflightCostMicroUsd,
  usageCostMicroUsd,
  type Usage,
} from "./ledger.ts";
import { logEntry, type ProxyLogEntry } from "./redact.ts";

export const DEFAULT_UPSTREAM = "https://api.anthropic.com";
export const ANTHROPIC_VERSION = "2023-06-01";
export const DEFAULT_MAX_BODY_BYTES = 8 * 1024 * 1024;
export const DEFAULT_MAX_RESPONSE_BYTES = 64 * 1024 * 1024;
const UPSTREAM_TIMEOUT_MS = 10 * 60 * 1000;
const MIN_TOKEN_LENGTH = 32;
const LOOPBACK_HOSTS = new Set(["127.0.0.1", "[::1]", "localhost"]);

const PATHS = new Set(["/v1/messages", "/v1/messages/count_tokens"]);
/**
 * Client headers that may reach upstream; everything else is dropped.
 * `anthropic-beta` is not forwarded in M1: a beta can change billing or add
 * server tools the price table does not know.
 */
const FORWARD_REQUEST_HEADERS = ["content-type", "accept"];
const FORWARD_RESPONSE_HEADERS = ["content-type", "request-id", "retry-after"];

export interface ProxyOptions {
  /** Per-run bearer token, generated by the caller. */
  token: string;
  /** The Anthropic key, held in memory only (see keychain.ts). */
  apiKey: string;
  runId: string;
  ledger: SpendLedger;
  upstreamBaseUrl?: string;
  maxBodyBytes?: number;
  maxResponseBytes?: number;
  log?: (entry: ProxyLogEntry) => void;
}

export interface RunningProxy {
  readonly host: "127.0.0.1";
  /** The address the socket is bound to, from `server.address()`. */
  readonly address: string;
  readonly port: number;
  readonly url: string;
  close(): Promise<void>;
}

const digest = (value: string) => createHash("sha256").update(value).digest();

/** Constant-time check of an Authorization header against the run token. */
function tokenOk(header: string | undefined, token: string): boolean {
  const match = /^Bearer (.+)$/u.exec(header ?? "");
  const presented = match?.[1] ?? "";
  // Hash both sides so the compare has equal lengths whatever was sent.
  return timingSafeEqual(digest(presented), digest(token)) && match !== null;
}

function send(
  res: ServerResponse,
  status: number,
  type: string,
  message: string,
  extra = {},
): void {
  const body = JSON.stringify({
    type: "error",
    error: { type, message, ...extra },
  });
  res.writeHead(status, {
    "content-type": "application/json",
    "content-length": Buffer.byteLength(body),
    ...(status === 413 ? { connection: "close" } : {}),
  });
  res.end(body);
}

class TooLarge extends Error {}

function readBody(req: IncomingMessage, max: number): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    let size = 0;
    req.on("data", (chunk: Buffer) => {
      size += chunk.length;
      if (size > max) {
        // Stop buffering; the 413 reply closes the connection.
        if (size - chunk.length <= max) reject(new TooLarge());
        chunks.length = 0;
        return;
      }
      chunks.push(chunk);
    });
    req.on("end", () => {
      resolve(Buffer.concat(chunks));
    });
    req.on("error", reject);
  });
}

interface UpstreamReply {
  status: number;
  headers: Record<string, string>;
  body: Buffer;
}

function forward(
  base: URL,
  path: string,
  headers: Record<string, string>,
  body: Buffer,
  maxResponseBytes: number,
): Promise<UpstreamReply> {
  const send = base.protocol === "https:" ? httpsRequest : httpRequest;
  return new Promise((resolve, reject) => {
    const req = send(
      {
        protocol: base.protocol,
        // URL keeps the brackets of an IPv6 literal; the socket layer wants none.
        hostname: base.hostname.replace(/^\[|\]$/gu, ""),
        port: base.port === "" ? undefined : base.port,
        method: "POST",
        path,
        headers: { ...headers, host: base.host, "content-length": body.length },
        agent: new Agent({ keepAlive: false }),
        timeout: UPSTREAM_TIMEOUT_MS,
      },
      (res) => {
        const chunks: Buffer[] = [];
        let size = 0;
        res.on("data", (chunk: Buffer) => {
          size += chunk.length;
          if (size > maxResponseBytes) {
            reject(new Error("upstream response too large"));
            req.destroy();
            return;
          }
          chunks.push(chunk);
        });
        res.on("end", () => {
          const out: Record<string, string> = {};
          for (const name of FORWARD_RESPONSE_HEADERS) {
            const value = res.headers[name];
            if (typeof value === "string") out[name] = value;
          }
          resolve({
            status: res.statusCode ?? 502,
            headers: out,
            body: Buffer.concat(chunks),
          });
        });
        res.on("error", reject);
      },
    );
    req.on("timeout", () => req.destroy(new Error("upstream timeout")));
    req.on("error", reject);
    req.end(body);
  });
}

const isLoopback = (addr: string | undefined) =>
  addr === "127.0.0.1" || addr === "::ffff:127.0.0.1";

/**
 * What to charge when the upstream call fails with `code`. Only a failure before
 * the socket connected (ECONNREFUSED, ENOTFOUND) proves nothing was sent; any
 * other error may have been billed, so the worst case is charged. On a flaky
 * network this overcharges the local ledger, never undercharges it.
 */
export function chargeForUpstreamError(
  code: string | undefined,
  worstCaseMicroUsd: number,
): number {
  return code === "ECONNREFUSED" || code === "ENOTFOUND"
    ? 0
    : worstCaseMicroUsd;
}

/** Start the credential proxy on 127.0.0.1 and an ephemeral port. */
export async function startProxy(options: ProxyOptions): Promise<RunningProxy> {
  if (options.token.length < MIN_TOKEN_LENGTH) {
    throw new Error(
      `the proxy token must be at least ${String(MIN_TOKEN_LENGTH)} characters`,
    );
  }
  const base = new URL(options.upstreamBaseUrl ?? DEFAULT_UPSTREAM);
  if (base.protocol !== "https:" && base.protocol !== "http:") {
    throw new Error("the upstream must be an http or https URL");
  }
  if (base.protocol === "http:" && !LOOPBACK_HOSTS.has(base.hostname)) {
    throw new Error("plain http is allowed only to a loopback upstream");
  }
  // Allowlist, not denylist: while prices are unverified only a loopback
  // upstream is allowed, so no spelling of the real API host can slip through.
  if (!PRICES_VERIFIED && !LOOPBACK_HOSTS.has(base.hostname)) {
    throw new Error(
      "refusing a non-loopback upstream: model prices are not verified (PRICES_VERIFIED)",
    );
  }
  if (process.env["NODE_TLS_REJECT_UNAUTHORIZED"] === "0") {
    throw new Error(
      "refusing to start: TLS verification is disabled (NODE_TLS_REJECT_UNAUTHORIZED=0)",
    );
  }
  const maxBody = options.maxBodyBytes ?? DEFAULT_MAX_BODY_BYTES;
  const maxResponse = options.maxResponseBytes ?? DEFAULT_MAX_RESPONSE_BYTES;
  const log = options.log ?? (() => undefined);
  /** The Host values a local client may send: filled once the port is known. */
  const hosts = new Set<string>();

  const handle = async (
    req: IncomingMessage,
    res: ServerResponse,
  ): Promise<void> => {
    const started = Date.now();
    if (!isLoopback(req.socket.remoteAddress)) {
      send(res, 403, "forbidden", "local clients only");
      return;
    }
    if (!hosts.has(req.headers.host ?? "")) {
      send(res, 403, "forbidden", "host not allowed");
      return;
    }
    if (!tokenOk(req.headers.authorization, options.token)) {
      send(res, 401, "authentication_error", "invalid or missing token");
      return;
    }
    const path = req.url ?? "";
    if (!PATHS.has(path)) {
      send(res, 404, "not_found_error", "path not allowed");
      return;
    }
    if (req.method !== "POST") {
      send(res, 405, "invalid_request_error", "method not allowed");
      return;
    }
    let body: Buffer;
    try {
      body = await readBody(req, maxBody);
    } catch (error) {
      if (error instanceof TooLarge) {
        send(res, 413, "request_too_large", "request body too large");
      }
      return;
    }
    let parsed: { model?: unknown; max_tokens?: unknown; stream?: unknown };
    try {
      const value: unknown = JSON.parse(body.toString("utf8"));
      if (typeof value !== "object" || value === null || Array.isArray(value)) {
        throw new Error("not an object");
      }
      parsed = value;
      // Forward the canonical re-serialisation, never the raw bytes: duplicate
      // keys or odd encodings cannot make the sent fields differ from the priced
      // ones. A body that cannot be re-serialised is a 400, not a 500.
      body = Buffer.from(JSON.stringify(parsed), "utf8");
    } catch {
      send(res, 400, "invalid_request_error", "body is not a JSON object");
      return;
    }
    const requestSha256 = createHash("sha256").update(body).digest("hex");
    const requested = typeof parsed.model === "string" ? parsed.model : "";
    const model = priceOf(requested) === undefined ? "unpriced" : requested;
    const record = (status: number, tokens: Usage, cost: number) => {
      log(
        logEntry({
          runId: options.runId,
          model,
          tokens: {
            input: tokens.input_tokens ?? 0,
            output: tokens.output_tokens ?? 0,
          },
          cost,
          status,
          latencyMs: Date.now() - started,
          requestSha256,
        }),
      );
    };
    const reject = (
      status: number,
      type: string,
      message: string,
      extra = {},
    ) => {
      record(status, {}, 0);
      send(res, status, type, message, extra);
    };
    if (parsed.stream === true) {
      reject(
        400,
        "invalid_request_error",
        "streaming is not supported by this proxy yet",
      );
      return;
    }

    const counting = path.endsWith("/count_tokens");
    let reservation: string | undefined;
    let worstCase = 0;
    if (!counting) {
      const maxTokens = parsed.max_tokens;
      if (
        typeof maxTokens !== "number" ||
        !Number.isInteger(maxTokens) ||
        maxTokens < 1
      ) {
        reject(
          400,
          "invalid_request_error",
          "max_tokens must be a positive integer",
        );
        return;
      }
      const cost = preflightCostMicroUsd(requested, maxTokens, body.length);
      if (cost === undefined) {
        reject(400, "invalid_request_error", "model has no pinned price");
        return;
      }
      worstCase = cost;
      const held = options.ledger.reserve(options.runId, cost);
      if (!held.ok) {
        reject(
          402,
          "helmwright_spend_cap",
          `${held.scope} spend cap would be exceeded`,
          {
            scope: held.scope,
            capMicroUsd: held.capMicroUsd,
            remainingMicroUsd: held.remainingMicroUsd,
          },
        );
        return;
      }
      reservation = held.id;
    }

    const headers: Record<string, string> = {};
    for (const name of FORWARD_REQUEST_HEADERS) {
      const value = req.headers[name];
      if (typeof value === "string") headers[name] = value;
    }
    headers["x-api-key"] = options.apiKey;
    headers["anthropic-version"] = ANTHROPIC_VERSION;

    /**
     * Settle after a call. If the ledger throws, the call is still logged with
     * its cost, the hold stays in the file, and the client gets a 500.
     */
    const settleOrFail = (
      id: string,
      charge: number,
      status: number,
      tokens: Usage,
    ): boolean => {
      try {
        options.ledger.settle(id, charge);
        return true;
      } catch {
        record(status, tokens, charge);
        send(res, 500, "api_error", "spend ledger error");
        return false;
      }
    };

    let upstream: UpstreamReply;
    try {
      upstream = await forward(base, path, headers, body, maxResponse);
    } catch (error) {
      // Only a failure before the socket connected proves nothing was billed;
      // any other error may have been billed, so the worst case is charged.
      const charge = chargeForUpstreamError(
        (error as NodeJS.ErrnoException).code,
        worstCase,
      );
      if (
        reservation !== undefined &&
        !settleOrFail(reservation, charge, 502, {})
      ) {
        return;
      }
      record(502, {}, charge);
      send(res, 502, "api_error", "upstream unreachable");
      return;
    }

    let usage: Usage = {};
    let cost = 0;
    if (reservation !== undefined) {
      const ok = upstream.status >= 200 && upstream.status < 300;
      if (ok) {
        try {
          usage =
            (JSON.parse(upstream.body.toString("utf8")) as { usage?: Usage })
              .usage ?? {};
        } catch {
          usage = {};
        }
        cost = usageCostMicroUsd(model, usage) ?? worstCase;
        // A success with no usage is billed at the worst case.
        if (
          usage.input_tokens === undefined &&
          usage.output_tokens === undefined
        )
          cost = worstCase;
      }
      // Settle the actual cost, even above the hold: it was spent.
      if (!settleOrFail(reservation, cost, upstream.status, usage)) return;
    }
    if (upstream.status >= 300 && upstream.status < 400) {
      record(502, usage, cost);
      send(res, 502, "api_error", "upstream redirect refused");
      return;
    }
    record(upstream.status, usage, cost);
    res.writeHead(upstream.status, {
      ...upstream.headers,
      "content-length": upstream.body.length,
    });
    res.end(upstream.body);
  };

  const server = createServer((req, res) => {
    handle(req, res).catch(() => {
      if (!res.headersSent) send(res, 500, "api_error", "proxy error");
      else res.destroy();
    });
  });
  server.keepAliveTimeout = 1000;
  await new Promise<void>((resolve, reject) => {
    server.once("error", reject);
    server.listen(0, "127.0.0.1", resolve);
  });
  const bound = server.address() as AddressInfo;
  const port = bound.port;
  hosts.add(`127.0.0.1:${String(port)}`);
  hosts.add(`localhost:${String(port)}`);
  return {
    host: "127.0.0.1",
    address: bound.address,
    port,
    url: `http://127.0.0.1:${String(port)}`,
    close: () =>
      new Promise<void>((resolve) => {
        server.close(() => {
          resolve();
        });
        server.closeAllConnections();
      }),
  };
}
